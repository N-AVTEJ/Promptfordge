/**
 * Get module by ID or slug.
 */
export function getModuleById(identifier: string): CurriculumModule | undefined {
  return CURRICULUM_MODULES.find(
    (m) => m.id === identifier || m.slug === identifier
  );
}

/**
 * Get specific lesson within a module, along with previous/next lesson links.
 */
export function getLessonById(
  moduleId: string,
  lessonId: string
): {
  module: CurriculumModule;
  lesson: Lesson;
  nextLesson?: { moduleId: string; lessonId: string; title: string };
  prevLesson?: { moduleId: string; lessonId: string; title: string };
  lessonIndex: number;
  totalLessons: number;
} | undefined {
  const currentModule = getModuleById(moduleId);
  if (!currentModule) return undefined;

  const lessonIndex = currentModule.lessons.findIndex((l) => l.id === lessonId);
  if (lessonIndex === -1) return undefined;

  const lesson = currentModule.lessons[lessonIndex];

  // Calculate next lesson (within module or next module)
  let nextLesson: { moduleId: string; lessonId: string; title: string } | undefined;
  if (lessonIndex < currentModule.lessons.length - 1) {
    const next = currentModule.lessons[lessonIndex + 1];
    nextLesson = { moduleId: currentModule.id, lessonId: next.id, title: next.title };
  } else {
    // Check if next module exists
    const nextModIndex = CURRICULUM_MODULES.findIndex((m) => m.id === currentModule.id) + 1;
    if (nextModIndex < CURRICULUM_MODULES.length && CURRICULUM_MODULES[nextModIndex].lessons.length > 0) {
      const nextMod = CURRICULUM_MODULES[nextModIndex];
      nextLesson = { moduleId: nextMod.id, lessonId: nextMod.lessons[0].id, title: nextMod.lessons[0].title };
    }
  }

  // Calculate prev lesson (within module or prev module)
  let prevLesson: { moduleId: string; lessonId: string; title: string } | undefined;
  if (lessonIndex > 0) {
    const prev = currentModule.lessons[lessonIndex - 1];
    prevLesson = { moduleId: currentModule.id, lessonId: prev.id, title: prev.title };
  } else {
    // Check if prev module exists
    const prevModIndex = CURRICULUM_MODULES.findIndex((m) => m.id === currentModule.id) - 1;
    if (prevModIndex >= 0 && CURRICULUM_MODULES[prevModIndex].lessons.length > 0) {
      const prevMod = CURRICULUM_MODULES[prevModIndex];
      const lastLes = prevMod.lessons[prevMod.lessons.length - 1];
      prevLesson = { moduleId: prevMod.id, lessonId: lastLes.id, title: lastLes.title };
    }
  }

  return {
    module: currentModule,
    lesson,
    nextLesson,
    prevLesson,
    lessonIndex,
    totalLessons: currentModule.lessons.length,
  };
}

/**
 * Flat list of all lessons across all modules.
 */
export function getAllLessons(): {
  module: CurriculumModule;
  lesson: Lesson;
}[] {
  const result: { module: CurriculumModule; lesson: Lesson }[] = [];
  for (const mod of CURRICULUM_MODULES) {
    for (const les of mod.lessons) {
      result.push({ module: mod, lesson: les });
    }
  }
  return result;
}
