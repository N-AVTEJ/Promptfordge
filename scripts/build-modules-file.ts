import * as fs from "node:fs";
import * as path from "node:path";
import { M1_M3 } from "./modules-data/m1-m3";
import { M4_M6 } from "./modules-data/m4-m6";
import { M7_M9 } from "./modules-data/m7-m9";
import { M10_M12 } from "./modules-data/m10-m12";
import type { CurriculumModule } from "./modules-data/types";

const ALL_MODULES: CurriculumModule[] = [
  ...M1_M3,
  ...M4_M6,
  ...M7_M9,
  ...M10_M12,
];

console.log(`Loaded ${ALL_MODULES.length} modules.`);

// Verify 12 modules
if (ALL_MODULES.length !== 12) {
  throw new Error(`Expected exactly 12 modules, got ${ALL_MODULES.length}`);
}

const EXPECTED_TITLES = [
  "Introduction to Prompt Engineering",
  "Example and Instruction Based Prompts",
  "Context Based and Interaction Based Prompts",
  "Advanced Prompt Techniques",
  "Prompt Optimization Techniques",
  "Multi-Model Prompting",
  "Tool-Augmented Prompting",
  "Security in Prompt Engineering",
  "Domain-Specific Prompt Engineering",
  "Advanced Prompt Engineering",
  "AI Agents, Context Engineering and MCP",
  "Production Prompt Engineering and Responsible AI",
];

ALL_MODULES.forEach((mod, idx) => {
  const expectedTitle = EXPECTED_TITLES[idx];
  if (mod.title !== expectedTitle) {
    throw new Error(`Module ${idx + 1} title mismatch. Expected: "${expectedTitle}", Got: "${mod.title}"`);
  }
  if (mod.quiz.length !== 5) {
    throw new Error(`Module ${mod.id} must have 5 quiz questions, got: ${mod.quiz.length}`);
  }
  mod.lessons.forEach((les, lIdx) => {
    if (les.quiz.length !== 5) {
      throw new Error(`Lesson ${les.id} must have 5 quiz questions, got: ${les.quiz.length}`);
    }
    if (les.chapters.length < 2) {
      throw new Error(`Lesson ${les.id} must have at least 2 chapters, got: ${les.chapters.length}`);
    }
  });

  // Calculate unique videoCount
  const videoIds = new Set<string>();
  mod.lessons.forEach((l) => {
    l.videos?.forEach((v) => {
      if (v.status === "ok") {
        videoIds.add(v.id);
      }
    });
  });
  mod.videoCount = videoIds.size;
  mod.lessonCount = mod.lessons.length;
});

// Construct the TypeScript code
const tsContent = `/**
 * PromptForge Curriculum — The 12 Comprehensive Engineering Modules
 * Strictly typed data in /content, never hardcoded in pages.
 * Generated by scripts/build-modules-file.ts
 */

export interface Chapter {
  time: number; // Time offset in seconds
  label: string;
}

export interface QuizQuestion {
  question: string;
  options: string[];
  answerIndex: number;
  explanation: string;
}

export interface PracticeChallenge {
  title: string;
  objective: string;
  instructions: string;
  starterPrompt: string;
  hint?: string;
  solutionNotes?: string;
}

export interface VideoSource {
  id: string;
  title: string;
  channel?: string;
  minutes?: number;
  covers: string[];
  role: "core" | "optional";
  status: "unverified" | "ok" | "unavailable";
  source: "external" | "own";
}

export interface Lesson {
  id: string;
  title: string;
  youtubeId: string; // Primary playable ID or empty string for slot
  status?: "ok" | "slot" | "unavailable";
  videos?: VideoSource[];
  chapters: Chapter[];
  summary: string;
  keyConcepts: string[];
  practiceChallenge: PracticeChallenge;
  quiz: QuizQuestion[];
  relatedLab: string;
  notesMarkdown?: string;
}

export interface CurriculumModule {
  id: string;
  number: number;
  slug: string;
  legacySlugs?: string[];
  title: string;
  subtitle: string;
  description: string;
  summary: string;
  outcome: string;
  duration: string;
  lessonCount: number;
  videoCount: number;
  level: "Foundational" | "Core" | "Advanced" | "Specialized";
  tags: string[];
  youtubeVideoId: string;
  accent: "amber" | "cyan";
  keyTakeaway: string;
  lessons: Lesson[];
  keyConcepts: string[];
  practiceChallenge: PracticeChallenge;
  quiz: QuizQuestion[];
}

export const CURRICULUM_MODULES: CurriculumModule[] = ${JSON.stringify(ALL_MODULES, null, 2)};

/**
 * Retrieve module by ID or Slug (including legacy slugs).
 */
export function getModuleById(identifier: string): CurriculumModule | undefined {
  if (!identifier) return undefined;
  const lower = identifier.toLowerCase().trim();
  return CURRICULUM_MODULES.find(
    (m) =>
      m.id.toLowerCase() === lower ||
      m.slug.toLowerCase() === lower ||
      (m.legacySlugs && m.legacySlugs.some((ls) => ls.toLowerCase() === lower))
  );
}

/**
 * Retrieve a specific lesson with contextual navigation (prev/next).
 */
export function getLessonById(
  moduleIdOrSlug: string,
  lessonId: string
): {
  module: CurriculumModule;
  lesson: Lesson;
  nextLesson?: { moduleId: string; lessonId: string; title: string };
  prevLesson?: { moduleId: string; lessonId: string; title: string };
  lessonIndex: number;
  totalLessons: number;
} | undefined {
  const currentModule = getModuleById(moduleIdOrSlug);
  if (!currentModule) return undefined;

  const lessonIndex = currentModule.lessons.findIndex((l) => l.id === lessonId);
  if (lessonIndex === -1) return undefined;

  const lesson = currentModule.lessons[lessonIndex];

  // Calculate next lesson (within module or next module)
  let nextLesson: { moduleId: string; lessonId: string; title: string } | undefined;
  if (lessonIndex < currentModule.lessons.length - 1) {
    const next = currentModule.lessons[lessonIndex + 1];
    nextLesson = { moduleId: currentModule.id, lessonId: next.id, title: next.title };
  } else {
    // Check if next module exists
    const nextModIndex = CURRICULUM_MODULES.findIndex((m) => m.id === currentModule.id) + 1;
    if (nextModIndex < CURRICULUM_MODULES.length && CURRICULUM_MODULES[nextModIndex].lessons.length > 0) {
      const nextMod = CURRICULUM_MODULES[nextModIndex];
      nextLesson = { moduleId: nextMod.id, lessonId: nextMod.lessons[0].id, title: nextMod.lessons[0].title };
    }
  }

  // Calculate prev lesson (within module or prev module)
  let prevLesson: { moduleId: string; lessonId: string; title: string } | undefined;
  if (lessonIndex > 0) {
    const prev = currentModule.lessons[lessonIndex - 1];
    prevLesson = { moduleId: currentModule.id, lessonId: prev.id, title: prev.title };
  } else {
    // Check if prev module exists
    const prevModIndex = CURRICULUM_MODULES.findIndex((m) => m.id === currentModule.id) - 1;
    if (prevModIndex >= 0 && CURRICULUM_MODULES[prevModIndex].lessons.length > 0) {
      const prevMod = CURRICULUM_MODULES[prevModIndex];
      const lastLes = prevMod.lessons[prevMod.lessons.length - 1];
      prevLesson = { moduleId: prevMod.id, lessonId: lastLes.id, title: lastLes.title };
    }
  }

  return {
    module: currentModule,
    lesson,
    nextLesson,
    prevLesson,
    lessonIndex,
    totalLessons: currentModule.lessons.length,
  };
}

/**
 * Flat list of all lessons across all modules.
 */
export function getAllLessons(): {
  module: CurriculumModule;
  lesson: Lesson;
}[] {
  const result: { module: CurriculumModule; lesson: Lesson }[] = [];
  for (const mod of CURRICULUM_MODULES) {
    for (const les of mod.lessons) {
      result.push({ module: mod, lesson: les });
    }
  }
  return result;
}

/**
 * Flat list of all modules.
 */
export function getAllModules(): CurriculumModule[] {
  return CURRICULUM_MODULES;
}
`;

const targetPath = path.resolve(process.cwd(), "content", "modules.ts");
fs.writeFileSync(targetPath, tsContent, "utf-8");
console.log(`Successfully generated content/modules.ts with 12 modules and ${ALL_MODULES.reduce((acc, m) => acc + m.lessons.length, 0)} lessons!`);
